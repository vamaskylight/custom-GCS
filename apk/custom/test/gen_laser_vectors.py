def num(v) -> str:
    return repr(float(v))


def main() -> int:
    lines = ["// Generated by gen_laser_vectors.py from vgcs/observe/geo_reference.py. Do not edit.", ""]
    for case in CASES:
        (lat, lon, hdg, roll, pitch, alt, gy, gp, rng, u, v, hfov, vfov) = case[:13]
        left_positive = bool(case[13]) if len(case) > 13 else False
        r = compute_lrf_slant_geo(
            vehicle_lat=lat, vehicle_lon=lon, vehicle_heading_deg=hdg,
            vehicle_roll_deg=roll, vehicle_pitch_deg=pitch, vehicle_alt_msl_m=alt,
            gimbal_yaw_deg=gy, gimbal_pitch_deg=gp, gimbal_yaw_left_positive=left_positive, slant_range_m=rng,
            video_x_norm=u, video_y_norm=v, gps_fix_type=3, gps_hdop=0.8,
            camera_hfov_deg=hfov, camera_vfov_deg=vfov,
        )
        geometric = r.target_lat is not None
        alt_arg = "std::nullopt" if alt is None else num(alt)
        vfov_arg = "std::nullopt" if vfov is None else num(vfov)
        exp_alt_has = "true" if r.target_alt_m is not None else "false"
        exp_alt = num(r.target_alt_m if r.target_alt_m is not None else 0.0)
        lines.append(
            "checkLaser(__LINE__, makeInput(" + ", ".join([num(lat), num(lon), num(hdg), num(roll), num(pitch), alt_arg,
                                          num(gy), num(gp), num(rng), num(u), num(v), num(hfov), vfov_arg,
                                          "true" if left_positive else "false"]) + "), "
            + ("true" if geometric else "false") + ", "
            + ", ".join([num(r.target_lat or 0.0), num(r.target_lon or 0.0), exp_alt_has, exp_alt,
                         num(r.horizontal_range_m or 0.0), num(r.depression_deg or 0.0), num(r.bearing_deg or 0.0)])
            + ");"
        )
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}: {len(CASES)} cases")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
